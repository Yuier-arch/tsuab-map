const CampusApp = {
    map: null,
    activePlace: null,
    isPanelExpanded: false,
    initialCenter: [2443, 3541],
    initialZoom: 1,

    init() {
        this.initMap();
        this.renderZones();
        this.bindEvents();
        this.bindSwipe();
    },

    initMap() {
        const w = 9099, h = 7332;
        const bounds = [[0, 0], [h, w]];

        this.map = L.map('map', {
            crs: L.CRS.Simple,
            minZoom: -2,
            maxZoom: 2,
            zoomControl: false,
            zoomAnimation: true,
            markerZoomAnimation: true,
            inertia: true,
            inertiaDeceleration: 3000,
            inertiaMaxSpeed: 2000,
            maxBounds: bounds,
            maxBoundsViscosity: 1.0
        });

        L.control.zoom({ position: 'topright' }).addTo(this.map);
        L.imageOverlay('map.png', bounds).addTo(this.map);
        this.map.fitBounds(bounds);

        setTimeout(() => {
            this.map.flyTo(this.initialCenter, this.initialZoom, { duration: 1 });
        }, 800);
    },

   renderZones() {
    const self = this;

    places.forEach(place => {
        let layer;

        if (place.shape === 'polygon' && place.polygon.length >= 3) {
            layer = L.polygon(place.polygon, {
                color: 'transparent',
                fillColor: '#000',
                fillOpacity: 0.01,
                opacity: 0,
                weight: 1,
                interactive: true
            });
        } else if (place.shape === 'circle' && place.coords) {
            layer = L.circle([place.coords[0], place.coords[1]], {
                radius: place.radius || 25,
                color: 'transparent',
                fillColor: '#000',
                fillOpacity: 0.01,
                opacity: 0,
                weight: 1,
                interactive: true
            });
        } else {
            return;
        }

        layer.addTo(this.map);
        layer.bringToFront();

        layer.on('add', function() {
            const el = this.getElement();
            if (el) {
                el.style.pointerEvents = 'auto';
                el.style.cursor = 'pointer';
            }
        });

        layer.on('click', (e) => {
            L.DomEvent.stopPropagation(e);
            self.selectPlace(place);
        });

        layer.on('touchstart', (e) => {
            L.DomEvent.stopPropagation(e);
            self.selectPlace(place);
        });
    });
},


    selectPlace(place) {
        this.activePlace = place;
        this.showPanel(place);
        this.map.flyTo(place._center, place.zoomLevel || 2, { duration: 2 });
        document.getElementById('reset-view-btn').classList.add('visible');
    },

    showPanel(place) {
        const badge = document.getElementById('panel-badge');
        badge.textContent = place.type;
        badge.style.background = CONFIG.badgeBg[place.type] || '#4a90d9';
        badge.style.color = CONFIG.badgeText[place.type] || '#fff';

        document.getElementById('panel-title').textContent = place.name;

        const addr = document.getElementById('panel-address');
        if (place.address) {
            addr.textContent = 'Адрес: ' + place.address;
            addr.style.display = 'block';
        } else {
            addr.style.display = 'none';
        }

        document.getElementById('panel-desc').textContent = place.desc && place.desc !== '...' ? place.desc : 'Нет описания';

        const extra = document.getElementById('panel-extra');
extra.innerHTML = `
    <p><strong>Категория:</strong> ${place.category}</p>
`;

        document.getElementById('info-panel').classList.add('active');
        this.isPanelExpanded = false;
        document.getElementById('info-panel').classList.remove('expanded');
    },

    closePanel() {
        document.getElementById('info-panel').classList.remove('active', 'expanded');
        this.isPanelExpanded = false;
        this.activePlace = null;

        const c = this.map.getCenter();
        this.map.flyTo([c.lat, c.lng], this.initialZoom, { duration: 1 });
        document.getElementById('reset-view-btn').classList.remove('visible');
    },

    resetView() {
        this.closePanel();
        this.map.flyTo(this.initialCenter, this.initialZoom, { duration: 1 });
    },

    bindSwipe() {
        const panel = document.getElementById('info-panel');
        let startY = 0;

        panel.addEventListener('touchstart', (e) => {
            startY = e.touches[0].clientY;
        });

        panel.addEventListener('touchmove', (e) => {
            const d = e.touches[0].clientY - startY;
            if (d > 60 && !this.isPanelExpanded) {
                this.closePanel();
            } else if (d < -60 && !this.isPanelExpanded) {
                panel.classList.add('expanded');
                this.isPanelExpanded = true;
            } else if (d > 60 && this.isPanelExpanded) {
                panel.classList.remove('expanded');
                this.isPanelExpanded = false;
            }
        });
    },

    bindEvents() {
        this.map.on('click', () => {
            if (this.activePlace) this.closePanel();
        });

        document.addEventListener('keydown', (e) => {
            if (e.key === 'Escape') {
                this.closeAllMenus();
                if (this.activePlace) this.closePanel();
            }
        });
    },

    openMenu() {
        document.getElementById('side-menu').classList.add('active');
        document.getElementById('menu-overlay').classList.add('active');
    },

    closeAllMenus() {
    document.getElementById('side-menu').classList.remove('active');
    document.getElementById('submenu').classList.remove('active');
    document.getElementById('menu-overlay').classList.remove('active');
    
    const res = document.getElementById('search-results');
    if (res) {
        res.classList.remove('active');
        res.innerHTML = '';
    }
    const input = document.getElementById('search-input');
    if (input) input.value = '';
},

    openSubmenu(category) {
        const names = {
            корпуса: 'Корпуса',
            общежития: 'Общежития',
            спорт: 'Спорткомплекс',
            магазины: 'Магазины',
            остановки: 'Остановки'
        };
        document.getElementById('submenu-title').textContent = names[category] || category;

        const items = places.filter(p => p.category === category);
        document.getElementById('submenu-items').innerHTML = items.map(p => `
    <div class="submenu-item" onclick="CampusApp.goTo('${p.name.replace(/'/g, "\\'")}')">
        <span class="color-dot" style="background:${p._color}"></span>
        <div>
            <div>${p.name}</div>
            ${p.address ? `<div style="font-size:12px;color:#999;margin-top:2px;">${p.address}</div>` : ''}
        </div>
    </div>
`).join('');

        document.getElementById('submenu').classList.add('active');
        document.getElementById('side-menu').classList.remove('active');
    },

    closeSubmenu() {
        document.getElementById('submenu').classList.remove('active');
        document.getElementById('side-menu').classList.add('active');
    },

    goTo(name) {
        const place = places.find(p => p.name === name);
        if (place) {
            this.closeAllMenus();
            this.selectPlace(place);
        }
    },

   handleSearch(query) {
    const q = query.trim().toLowerCase();
    const res = document.getElementById('search-results');

    if (!q) {
        res.classList.remove('active');
        res.innerHTML = '';
        return;
    }

    const found = places.filter(p =>
        p.name.toLowerCase().includes(q) ||
        (p.address && p.address.toLowerCase().includes(q))
    );

    res.classList.add('active');
    
    if (found.length === 0) {
        res.innerHTML = '<div class="search-empty">Ничего не найдено</div>';
    } else {
        res.innerHTML = found.map(p => `
            <div class="submenu-item" onclick="CampusApp.goTo('${p.name.replace(/'/g, "\\'")}')">
                <span class="color-dot" style="background:${p._color}"></span>
                <div>
                    <div>${p.name}</div>
                    ${p.address ? `<div style="font-size:12px;color:#999;margin-top:2px;">${p.address}</div>` : ''}
                </div>
            </div>
        `).join('');
    }
}
};

// Запуск
document.addEventListener('DOMContentLoaded', () => CampusApp.init());
