places.forEach(place => {
    if (place.shape === 'polygon') {
        const sumY = place.polygon.reduce((s, p) => s + p[0], 0);
        const sumX = place.polygon.reduce((s, p) => s + p[1], 0);
        place._center = [sumY / place.polygon.length, sumX / place.polygon.length];
    } else {
        place._center = [place.coords[0], place.coords[1]];
    }
    place._color = CONFIG.colors[place.category] || '#999';
});

